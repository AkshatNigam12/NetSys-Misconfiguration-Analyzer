"""
PDF Report Generator for Analyzer2.
Generates professional misconfiguration reports using FPDF.
"""

import os
from datetime import datetime

from fpdf import FPDF


class ReportGenerator:
    """Generates PDF reports from scan results."""

    def __init__(self, report_directory="reports"):
        self.report_directory = report_directory
        os.makedirs(self.report_directory, exist_ok=True)

    def generate(self, network_issues, system_issues, misconfig_results=None):
        """Generate a PDF report and return the file path.

        Args:
            network_issues: List of dicts with network issue details.
            system_issues: List of dicts with system issue details.
            misconfig_results: Optional tuple from run_network_misconfig_scan().

        Returns:
            str: Path to the generated PDF file.
        """
        timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
        filename = f"scan_report_{timestamp}.pdf"
        filepath = os.path.join(self.report_directory, filename)

        pdf = FPDF()
        pdf.set_auto_page_break(auto=True, margin=15)
        pdf.add_page()

        # Title
        pdf.set_font("Helvetica", style="B", size=18)
        pdf.cell(0, 12, "Analyzer2 - Security Scan Report", align="C", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(5)

        # Timestamp
        pdf.set_font("Helvetica", size=10)
        pdf.set_text_color(100, 100, 100)
        pdf.cell(0, 8, f"Generated: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", align="C", new_x="LMARGIN", new_y="NEXT")
        pdf.set_text_color(0, 0, 0)
        pdf.ln(5)

        # Executive Summary
        total_issues = len(network_issues) + len(system_issues)
        high_risk = sum(
            1 for issue in (network_issues + system_issues)
            if isinstance(issue, dict) and issue.get("risk_level") == "High"
        )

        pdf.set_font("Helvetica", style="B", size=14)
        pdf.cell(0, 10, "Executive Summary", new_x="LMARGIN", new_y="NEXT")
        pdf.ln(3)

        pdf.set_font("Helvetica", size=11)
        summary = (
            f"Total Issues Found: {total_issues}\n"
            f"  - Network Issues: {len(network_issues)}\n"
            f"  - System Issues: {len(system_issues)}\n"
            f"  - High Risk: {high_risk}"
        )
        pdf.multi_cell(0, 7, summary)
        pdf.ln(5)

        # Network Issues
        self._add_section(pdf, "1. Network Misconfigurations", network_issues)

        # System Issues
        self._add_section(pdf, "2. System Misconfigurations", system_issues)

        # Best-Practice Comparison (from misconfig scanner)
        if misconfig_results:
            report_text, flagged, _, network_type = misconfig_results
            pdf.add_page()
            pdf.set_font("Helvetica", style="B", size=14)
            pdf.cell(0, 10, f"3. CIS/NIST Best-Practice Comparison ({network_type} Network)", new_x="LMARGIN", new_y="NEXT")
            pdf.ln(3)

            if flagged:
                for item in flagged:
                    pdf.set_font("Helvetica", style="B", size=11)
                    pdf.cell(0, 8, f"  {item['misconfiguration']}", new_x="LMARGIN", new_y="NEXT")

                    pdf.set_font("Helvetica", size=10)
                    detail = (
                        f"    Current: {item['current_value']}\n"
                        f"    Recommended: {item['recommended_value']}\n"
                        f"    Risk Level: {item['risk_level']}  |  Source: {item['source']}"
                    )
                    pdf.multi_cell(0, 6, detail)
                    pdf.ln(2)
            else:
                pdf.set_font("Helvetica", size=11)
                pdf.cell(0, 8, "  All checks passed - no misconfigurations detected.", new_x="LMARGIN", new_y="NEXT")

        # Footer
        pdf.ln(10)
        pdf.set_font("Helvetica", style="I", size=9)
        pdf.set_text_color(120, 120, 120)
        pdf.cell(0, 8, "Generated by Analyzer2 - Network & System Misconfiguration Scanner", align="C", new_x="LMARGIN", new_y="NEXT")

        try:
            pdf.output(filepath)
            return filepath
        except Exception as e:
            print(f"Error saving PDF report: {e}")
            return None

    def _add_section(self, pdf, title, issues):
        """Add a section of issues to the PDF."""
        pdf.ln(3)
        pdf.set_font("Helvetica", style="B", size=14)
        pdf.cell(0, 10, title, new_x="LMARGIN", new_y="NEXT")
        pdf.ln(3)

        if not issues:
            pdf.set_font("Helvetica", size=11)
            pdf.cell(0, 8, "  No issues detected.", new_x="LMARGIN", new_y="NEXT")
            return

        for issue in issues:
            if not isinstance(issue, dict):
                continue

            pdf.set_font("Helvetica", style="B", size=11)
            name = issue.get("name", "Unknown Issue")
            pdf.cell(0, 8, f"  {name}", new_x="LMARGIN", new_y="NEXT")

            pdf.set_font("Helvetica", size=10)
            detail = (
                f"    Status: {issue.get('current_status', 'N/A')}\n"
                f"    Risk Level: {issue.get('risk_level', 'N/A')}\n"
                f"    Description: {issue.get('description', 'N/A')}\n"
                f"    Suggested Fix: {issue.get('suggested_fix', 'N/A')}"
            )
            pdf.multi_cell(0, 6, detail)
            pdf.ln(2)
